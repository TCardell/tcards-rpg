import { test, expect } from '@playwright/test';

const save = page => page.evaluate(() => JSON.parse(localStorage.getItem('tcards.valbruma.local.v1')));
test('portada, orden móvil, fondo, paneles y preferencias no cambian la partida', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Tale Cards RPG' })).toBeVisible();
  await expect(page.getByText('PREALFA · v0.0.8')).toBeVisible();
  await page.getByRole('button', { name: 'Jugar en solitario' }).click();
  const initial = await save(page);
  await expect(page.locator('body')).toHaveAttribute('data-scenery','village');
  await expect(page.locator('.rail .adventure-nav')).toHaveCount(1);
  await page.setViewportSize({width:390,height:844});
  const nav = page.locator('.play > .adventure-nav');
  await expect(nav).toBeVisible();
  const card = page.locator('.sce-card');
  await expect(card).toHaveAttribute('data-instance',initial.cardInstanceId);
  expect((await nav.boundingBox()).y).toBeGreaterThan((await page.locator('.scene').boundingBox()).y + (await page.locator('.scene').boundingBox()).height - 1);
  await nav.getByRole('button',{name:'Mochila'}).click();
  await expect(page.locator('.capacity .filled')).toHaveCount(1);
  await expect(page.getByText('Tónico de hierbas × 1')).toBeVisible();
  await nav.getByRole('button',{name:'Mapa'}).click();
  await expect(page.locator('.map-center')).toHaveAttribute('aria-current','location');
  await nav.getByRole('button',{name:'Ajustes'}).click();
  await page.getByRole('combobox',{name:'Tema',exact:true}).selectOption('ember');
  await page.getByRole('combobox',{name:'Fondo ambiental'}).selectOption('off');
  await expect(page.locator('html')).toHaveAttribute('data-ambience','off');
  await expect(page.locator('html')).toHaveAttribute('data-theme','ember');
  expect(await save(page)).toEqual(initial);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(card).toHaveAttribute('data-instance',initial.cardInstanceId);
  await expect(page.locator('html')).toHaveAttribute('data-theme','ember');
  await expect(page.locator('html')).toHaveAttribute('data-ambience','off');
  await page.setViewportSize({width:1280,height:900});
  await expect(page.locator('.rail .adventure-nav')).toBeVisible();
  expect(await save(page)).toEqual(initial);
  await page.locator('[data-id=visit_inn]').click();
  await expect(page.locator('body')).toHaveAttribute('data-scenery','inn');
  await page.locator('[data-id=speak]').click();
  await expect(page.locator('body')).toHaveAttribute('data-scenery','inn');
  await expect(page.locator('.card-title')).toHaveText('Ivo, el posadero');
});
